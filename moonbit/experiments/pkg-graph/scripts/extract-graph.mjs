#!/usr/bin/env node
// Writes graph.json: the dependency graph of the MoonBit module's own
// packages, as `moon tree --package --json` reports it, annotated with the
// size of each package from `moon ide outline` (and from the file names).
//
// The registry's packages are not drawn: `moon tree` lists them too, but
// the graph we want is the one inside moonbit/, and the only import of
// them is the compare CLI's use of moonbitlang/async. Those edges are
// kept in "external" so that nothing is silently dropped.

import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../.."); // moonbit/, the module root
const out = resolve(here, "..", "graph.json");

// Packages generated by the blog's embed scripts rather than written by
// hand; they carry the posts and documents the site serves.
const GENERATED = new Set([
  "examples/blog/assets",
  "examples/blog/posts",
  "examples/blog/repodocs",
  "examples/blog/slops",
]);

function moon(args) {
  return execFileSync("moon", args, { cwd: root, encoding: "utf8" });
}

function projectName() {
  const text = readFileSync(join(root, "moon.mod"), "utf8");
  const m = text.match(/^\s*name\s*=\s*"([^"]+)"/m);
  if (!m) throw new Error("no name in moon.mod");
  return m[1];
}

// `moon ide outline` only knows the package in a target it is built for,
// so ask for the default target first and fall back to the others.
function outline(pkg) {
  for (const target of [null, "wasm-gc", "native", "js"]) {
    const args = ["ide", "outline"];
    if (target) args.push("--target", target);
    args.push(join(root, pkg));
    try {
      const text = execFileSync("moon", args, {
        cwd: root,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      });
      // A target the package is not built for answers "Error: ..." on
      // stdout and still exits 0, so look for a file header instead.
      if (/^\S+\.mbt:$/m.test(text)) return text;
    } catch {
      // try the next target
    }
  }
  return "";
}

const decl = /^\s*\d+ \|((?:pub\(all\)|pub|priv) )?(?:async )?(fn|struct|enum|type|typealias|impl|const|let|trait|extend|suberror|extern)\b/;

// Counts declarations per file the way `moon ide outline` groups them:
// a "name.mbt:" header followed by its declarations.
function countDeclarations(text) {
  const counts = new Map();
  let file = null;
  for (const line of text.split("\n")) {
    const header = line.match(/^(\S+\.mbt):$/);
    if (header) {
      file = header[1];
      counts.set(file, { declarations: 0, public: 0 });
      continue;
    }
    const m = line.match(decl);
    if (!m || !file) continue;
    const entry = counts.get(file);
    entry.declarations += 1;
    if (m[1]?.includes("pub")) entry.public += 1;
  }
  return counts;
}

function sizeOf(pkg) {
  const files = readdirSync(join(root, pkg)).filter((f) => f.endsWith(".mbt"));
  const isTest = (f) => f.endsWith("_test.mbt") || f.endsWith("_wbtest.mbt");
  const counts = countDeclarations(outline(pkg));
  const size = { files: 0, testFiles: 0, declarations: 0, public: 0 };
  for (const f of files) {
    const c = counts.get(f) ?? { declarations: 0, public: 0 };
    if (isTest(f)) {
      size.testFiles += 1;
    } else {
      size.files += 1;
      size.declarations += c.declarations;
      size.public += c.public;
    }
  }
  return size;
}

function kindOf(pkg) {
  if (GENERATED.has(pkg)) return "generated";
  if (pkg.startsWith("pkg/")) return "library";
  if (pkg.startsWith("examples/")) return "application";
  return "other";
}

const project = projectName();
const tree = JSON.parse(moon(["tree", "--package", "--json"]));
if (tree.status !== "success") {
  throw new Error(`moon tree failed: ${JSON.stringify(tree.error)}`);
}

const ours = new Set(
  tree.nodes.map((n, i) => (n.module === project ? i : -1)).filter((i) => i >= 0),
);
const nameOf = (i) => tree.nodes[i].rel;

const packages = [...ours].map((i) => {
  const name = nameOf(i);
  return { name, kind: kindOf(name), ...sizeOf(name) };
});
packages.sort((a, b) => a.name.localeCompare(b.name));

const edges = new Map();
const external = [];
for (const e of tree.edges) {
  if (!ours.has(e.from)) continue;
  if (!ours.has(e.to)) {
    external.push({
      from: nameOf(e.from),
      to: [tree.nodes[e.to].module, tree.nodes[e.to].rel].filter(Boolean).join("/"),
      kinds: e.kinds,
    });
    continue;
  }
  const key = `${nameOf(e.from)}\u0000${nameOf(e.to)}`;
  const kinds = edges.get(key) ?? new Set();
  for (const k of e.kinds) kinds.add(k);
  edges.set(key, kinds);
}

const graph = {
  project,
  generatedBy: "moon tree --package --json, annotated with moon ide outline",
  moonVersion: moon(["version"]).split("\n")[0].trim(),
  packages,
  edges: [...edges]
    .map(([key, kinds]) => {
      const [from, to] = key.split("\u0000");
      return { from, to, kinds: [...kinds].sort() };
    })
    .sort((a, b) => a.from.localeCompare(b.from) || a.to.localeCompare(b.to)),
  external: external.sort(
    (a, b) => a.from.localeCompare(b.from) || a.to.localeCompare(b.to),
  ),
};

writeFileSync(out, JSON.stringify(graph, null, 2) + "\n");
console.log(
  `${out}: ${packages.length} packages, ${graph.edges.length} edges, ${external.length} external`,
);
