// The graph from graph.json in the two notations we render: mermaid's
// flowchart syntax (also read by beautiful-mermaid) and D2's.
//
// Every node is a package of the MoonBit module; the edges are
// `source` (an import the package's code needs) or `blackbox-test`
// (only its tests need it, drawn dashed).

import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

export function loadGraph() {
  return JSON.parse(readFileSync(resolve(here, "..", "graph.json"), "utf8"));
}

// mermaid node ids cannot hold '/' or '-'.
export function idOf(name) {
  return name.replace(/[^A-Za-z0-9_]/g, "_");
}

const SHAPES = {
  library: (label) => `["${label}"]`,
  application: (label) => `("${label}")`,
  generated: (label) => `[("${label}")]`,
  other: (label) => `["${label}"]`,
};

const STYLES = {
  library: "fill:#e8f0fe,stroke:#1a73e8,color:#1a3a6b",
  application: "fill:#fff4e5,stroke:#e8710a,color:#7a3b00",
  generated: "fill:#f1f3f4,stroke:#9aa0a6,color:#3c4043,stroke-dasharray:4 3",
  other: "fill:#ffffff,stroke:#5f6368,color:#202124",
};

const D2_STYLES = {
  library: "{ style: { fill: \"#e8f0fe\"; stroke: \"#1a73e8\"; font-color: \"#1a3a6b\" } }",
  application: "{ style: { fill: \"#fff4e5\"; stroke: \"#e8710a\"; font-color: \"#7a3b00\" } }",
  generated: "{ style: { fill: \"#f1f3f4\"; stroke: \"#9aa0a6\"; font-color: \"#3c4043\"; stroke-dash: 4 } }",
  other: "{ style: { fill: \"#ffffff\"; stroke: \"#5f6368\"; font-color: \"#202124\" } }",
};

// Edges whose kinds include "source" are solid; the rest are dashed and
// labelled "test".
export function isTestOnly(edge) {
  return !edge.kinds.includes("source");
}

export function mermaidSource(graph, { direction = "LR" } = {}) {
  const lines = [
    "%% The packages of podhmo/html-sandbox/moonbit and their imports.",
    "%% Generated by experiments/pkg-graph/scripts/render-mermaid.mjs from graph.json.",
    `graph ${direction}`,
    "%% pkg/* are rectangles (libraries), examples/blog/* of the site and its",
    "%% CLIs are rounded (applications), and the packages the embed scripts",
    "%% generate are cylinders.",
  ];
  for (const p of graph.packages) {
    lines.push(`  ${idOf(p.name)}${SHAPES[p.kind](p.name)}`);
  }
  for (const kind of ["library", "application", "generated", "other"]) {
    const members = graph.packages.filter((p) => p.kind === kind);
    if (members.length === 0) continue;
    lines.push(`  classDef ${kind} ${STYLES[kind]}`);
    lines.push(`  class ${members.map((p) => idOf(p.name)).join(",")} ${kind}`);
  }
  for (const e of graph.edges) {
    const arrow = isTestOnly(e) ? '-. "test" .->' : "-->";
    lines.push(`  ${idOf(e.from)} ${arrow} ${idOf(e.to)}`);
  }
  return lines.join("\n") + "\n";
}

export function d2Source(graph, { direction = "right" } = {}) {
  const lines = [
    "# The packages of podhmo/html-sandbox/moonbit and their imports.",
    "# Generated by experiments/pkg-graph/scripts/render-d2.mjs from graph.json.",
    `direction: ${direction}`,
    "",
    "classes: {",
    ...Object.entries(D2_STYLES).map(([kind, style]) => `  ${kind}: ${style}`),
    "}",
    "",
  ];
  for (const p of graph.packages) {
    lines.push(`${idOf(p.name)}: "${p.name}" { class: ${p.kind} }`);
  }
  lines.push("");
  for (const e of graph.edges) {
    const from = idOf(e.from);
    const to = idOf(e.to);
    if (isTestOnly(e)) {
      lines.push(`${from} -> ${to}: "test" { style.stroke-dash: 3 }`);
    } else {
      lines.push(`${from} -> ${to}`);
    }
  }
  return lines.join("\n") + "\n";
}
