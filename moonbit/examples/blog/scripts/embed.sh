#!/bin/sh
# embed.sh writes OUT, a MoonBit source holding Markdown files as `files`,
# an array of (name, content) pairs sorted by name, the way go:embed gives
# the Go blog its posts and documents.
#
#   sh examples/blog/scripts/embed.sh OUT BASE [PATH...]
#
# With no PATH, it takes every *.md file directly in BASE, or every file of
# a directory named *.md directly in BASE (a bundle, given as dir/name).
# Each PATH is a file, or a directory whose files are all taken,
# subdirectories included, as long as they are *.md files, live under a
# *.md directory, or are metadata files named *.metadata.json (which may
# be absent); a PATH may be given relative to BASE or with BASE in front,
# and names are relative to BASE. list-files.sh picks the files, the same
# way for content.sh.
#
#   sh examples/blog/scripts/embed.sh examples/blog/posts/embedded.mbt ../posts
#   sh examples/blog/scripts/embed.sh examples/blog/repodocs/embedded.mbt .. ../TODO.md ../docs
#
# moon runs it before building through dev_build in the package's moon.pkg,
# and the Makefile runs it too: moon reruns it only when an input's mtime
# changes, which for a directory means a file added or removed directly in
# it, not a file edited or one in a subdirectory. OUT is rewritten only
# when its content changes, so running it again rebuilds nothing.
set -eu

out=$1
# moon passes paths as ./PATH; drop that so both callers write the same file.
base=${2#./}
shift 2
tmp=$out.tmp.$$
list=$out.list.$$
raw=$out.raw.$$
trap 'rm -f "$tmp" "$tmp.one" "$list" "$raw"' EXIT

LC_ALL=C
export LC_ALL

# Write the names to a file before sorting them, so a path list-files.sh
# rejects stops the build: in a pipeline, set -e sees only sort's status.
sh "$(dirname "$0")/list-files.sh" "$base" "$@" >"$raw"
sort -u -o "$list" "$raw"

{
  echo "// Code generated by scripts/embed.sh from $base; DO NOT EDIT."
  i=0
  while IFS= read -r name; do
    # moon tool embed is what moon.pkg's :embed runs; drop its header.
    moon tool embed --text -i "$base/$name" -o "$tmp.one" --name "file_$i"
    echo
    sed -n '/^\/\/\/|$/,$p' "$tmp.one"
    i=$((i + 1))
  done <"$list"
  echo
  echo '///|'
  echo "/// files holds the embedded files as pairs of the name, relative to"
  echo "/// $base, and the content, sorted by name."
  echo 'pub let files : ReadOnlyArray[(String, String)] = ['
  i=0
  while IFS= read -r name; do
    echo "  (\"$name\", file_$i),"
    i=$((i + 1))
  done <"$list"
  echo ']'
} >"$tmp"

if cmp -s "$tmp" "$out"; then
  rm -f "$tmp"
else
  mv "$tmp" "$out"
fi
